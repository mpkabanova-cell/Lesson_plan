export function gradeSuggestionKeys(grade: string): string[] {
  const gradeNumber = Number(grade);
  if (!Number.isFinite(gradeNumber)) return [];
  if (gradeNumber >= 1 && gradeNumber <= 4) return [grade, "1-4"];
  if (gradeNumber >= 5 && gradeNumber <= 6) return [grade, "5-6", "5-9"];
  if (gradeNumber >= 8 && gradeNumber <= 9) return [grade, "8-9", "7-9", "5-9"];
  if (gradeNumber === 7) return [grade, "7-9", "5-9"];
  if (gradeNumber >= 10 && gradeNumber <= 11) return [grade, "10-11"];
  return [grade];
}

export function getTopicSuggestions(subject: string, grade: string): string[] {
  const subjectSuggestions = TOPIC_SUGGESTIONS_BY_SUBJECT[subject];
  if (!subjectSuggestions) return [...UNIVERSAL_TOPIC_SUGGESTIONS];
  for (const key of gradeSuggestionKeys(grade)) {
    const topics = subjectSuggestions[key];
    if (topics && topics.length > 0) return topics;
  }
  return subjectSuggestions.default.length > 0
    ? subjectSuggestions.default
    : [...UNIVERSAL_TOPIC_SUGGESTIONS];
}

/** Тема из саджестов другого класса того же предмета (например, Пифагор в 7 вместо 8). */
export function isCuratedTopicForAnotherGrade(
  subject: string,
  grade: string,
  topic: string,
): boolean {
  const trimmed = topic.trim();
  if (!trimmed) return false;
  if (getTopicSuggestions(subject, grade).includes(trimmed)) return false;

  const subjectSuggestions = TOPIC_SUGGESTIONS_BY_SUBJECT[subject];
  if (!subjectSuggestions) return false;

  for (const [key, values] of Object.entries(subjectSuggestions)) {
    if (key === "default" || key === grade || !values) continue;
    if (values.includes(trimmed)) return true;
  }
  return false;
}

/** Очищает устаревшую тему из автосохранения, если она относится к другому классу. */
export function sanitizeTopicForGrade(subject: string, grade: string, topic: string): string {
  const trimmed = topic.trim();
  if (!trimmed) return "";
  return isCuratedTopicForAnotherGrade(subject, grade, trimmed) ? "" : trimmed;
}
